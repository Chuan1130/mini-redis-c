#pragma once

/*
 * 本文件属于哪一章：
 * - ch08：围绕字符串 KV 主线，加入最小快照持久化
 *
 * 本文件负责什么：
 * - 声明快照保存和加载接口
 * - 约定当前项目默认使用哪个快照文件名
 * - 让服务端主程序知道如何在启动时恢复数据库、在命令层里触发保存
 *
 * 本文件和其他文件如何配合：
 * - src/persist.c：真正实现保存和加载逻辑
 * - src/tcp_server.c：启动时调用 persist_load，收到 SAVE 时调用 persist_save
 * - db.*：继续只负责内存数据结构本身，persist.* 只是在遍历它
 */

#include "db.h"

#define SNAPSHOT_FILE "my_redis.dump"

/*
 * 把当前数据库保存到本地快照文件。
 *
 * 参数：
 * - db：要保存的数据库
 * - path：目标文件路径
 *
 * 返回值：
 * - 0：保存成功
 * - -1：保存失败
 *
 * 说明：
 * - 保存时会跳过已经过期的数据
 * - 当前采用“覆盖写整个快照文件”的最小方式
 */
int persist_save(const Db *db, const char *path);

/*
 * 从本地快照文件加载数据库。
 *
 * 参数：
 * - db：目标数据库，加载成功后会被替换成文件中的内容
 * - path：源文件路径
 *
 * 返回值：
 * - 0：加载成功
 * - 1：文件不存在，这不算错误，表示当前没有历史快照
 * - -1：加载失败，例如文件损坏或读写错误
 *
 * 说明：
 * - 加载时会跳过文件中已经过期的数据
 * - 如果加载失败，函数会尽量保持原数据库不被半途污染
 */
int persist_load(Db *db, const char *path);
